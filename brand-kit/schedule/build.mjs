#!/usr/bin/env node
// brand-kit/schedule/build.mjs
//
// Turns posts.mjs into everything the owner (or a scheduler) posts from:
//   brand-kit/phone/DAILY-POSTS.txt       the day-by-day list for posting by hand
//   brand-kit/phone/platforms/*.txt       exact text per app, all days
//   brand-kit/schedule/metricool-queue.json  one entry per app post
//
// Usage (from the repo root):
//   node brand-kit/schedule/build.mjs                     rewrite all of the above
//   node brand-kit/schedule/build.mjs --check             exit 1 if any of them is stale
//   node brand-kit/schedule/build.mjs --start=2026-10-20  print a dated copy of the queue
//   node brand-kit/schedule/build.mjs --start=2026-10-20 --out=/tmp/queue.json
//
// The committed queue holds day offsets, never calendar dates, so building
// twice gives byte-identical output and a reviewer sees only real changes.
// Dates are applied once, when someone actually schedules, with --start;
// that mode writes the dated copy and nothing else.
//
// Nothing here talks to Metricool or any social network. It only writes
// files. See README.md for how the queue maps onto Metricool and why nothing
// is scheduled until the owner has linked the accounts.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { basename, dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SLOTS, EXTRAS, PLATFORM_FILES } from './posts.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '../..');
const phoneDir = join(repo, 'brand-kit/phone');

const SITE = 'https://learnwithlexis.com';
const TZ = 'Asia/Bangkok';
// Thailand has no daylight saving, so a fixed offset is exact all year.
const TZ_OFFSET = '+07:00';
const WINDOW = ['19:00', '21:00'];

// Posting order and time per app. TikTok first because DAILY-POSTS.txt has
// always said so; half an hour apart so the four posts of one day don't land
// in the same minute, and all inside the 19:00-21:00 window the platform
// files ask for.
//   bioTail    the caption ends "ลิงก์ในโปรไฟล์" / "Link in bio.", because a
//              link in the caption can't be clicked there. TikTok and Instagram
//              never linked captions, and YouTube stopped linking URLs in Shorts
//              descriptions in Aug 2023, so a viewer's only working path is
//              the profile link.
//   linkInText the tracked URL is printed in the text. On Facebook it is the
//              click; on YouTube it is visible text that keeps the UTM if
//              copied, which is why the old YouTube.txt kept it too.
//   hashtags   only where the old platform files used them.
const NETWORKS = {
  tiktok: { label: 'TikTok', time: '19:00', bioTail: true, linkInText: false, hashtags: true },
  instagram: { label: 'Instagram', time: '19:30', bioTail: true, linkInText: false, hashtags: true },
  youtube: { label: 'YouTube', time: '20:00', bioTail: true, linkInText: true, hashtags: false },
  facebook: { label: 'Facebook', time: '20:30', bioTail: false, linkInText: true, hashtags: false },
};
const ORDER = Object.keys(NETWORKS);
const LINE_TIME = '19:00';
// A second caption language shows on these only, as the Instagram and
// Facebook pages always did. TikTok and Shorts keep one language per post.
const BILINGUAL = new Set(['instagram', 'facebook']);
const BIO_TAIL = { th: 'ลิงก์ในโปรไฟล์', en: 'Link in bio.' };
const UTM_KEYS = ['utm_source', 'utm_medium', 'utm_campaign', 'utm_content'];
const GENERATED = 'Generated by brand-kit/schedule/build.mjs from posts.mjs. To change a caption, edit posts.mjs and rebuild; edits made here are overwritten.';

// Metricool's own flags, sent as-is in createScheduledPost's networkData.
//
// The AI-content flags are all on because every reel carries an
// ElevenLabs narrator or LEXIS's own generated video. Declaring it is
// what the apps ask for, and it keeps faith with the rule that nothing may
// imply a human is speaking. TikTok's commercialContentOwnBrand is on
// because every post promotes LEXIS itself, which TikTok requires to be
// disclosed.
function networkData(network, slot) {
  switch (network) {
    case 'tiktok': return { tiktokData: { title: slot.tiktokTitle, privacyOption: 'PUBLIC_TO_EVERYONE', commercialContentOwnBrand: true, isAigc: true } };
    case 'instagram': return { instagramData: { type: 'REEL', showReelOnFeed: true, isAiGenerated: true } };
    case 'youtube': return { youtubeData: { title: slot.youtubeTitle, type: 'short', privacy: 'public', madeForKids: false, category: 'EDUCATION', isAiGeneratedContent: true } };
    case 'facebook': return { facebookData: { type: 'REEL' } };
    default: throw new Error(`no Metricool data for ${network}`);
  }
}

const pad = (n) => String(n).padStart(2, '0');

function link(source, slot, path) {
  const q = new URLSearchParams({ utm_source: source, utm_medium: 'social', utm_campaign: 'daily-posts', utm_content: slot });
  return `${SITE}${path}?${q}`;
}

// ---------------------------------------------------------------- checks ---
// Every check fails the build rather than warning: a bad entry here becomes
// a public post the moment the queue is fired.

const problems = [];
const fail = (msg) => problems.push(msg);

// Landing paths must be real routes, read from App.jsx's switch by source
// text (importing it would pull in React). If the pattern ever stops
// matching, that is reported rather than every path passing silently.
const appSrc = readFileSync(join(repo, 'frontend/src/App.jsx'), 'utf8');
const ROUTES = new Set(['/', ...[...appSrc.matchAll(/case '(\/[^']*)'/g)].map((x) => x[1])]);
if (ROUTES.size < 5) fail('could not read the route list from frontend/src/App.jsx (the `case \'/path\'` pattern no longer matches)');

const seenDays = new Set();
const seenSlots = new Set();
const seenWeeks = new Set();
let prevDay = 0;
for (const s of SLOTS) {
  const at = `day ${s.day} (${s.slot})`;
  if (!Number.isInteger(s.day) || s.day < 1) fail(`${at}: day must be a positive integer`);
  if (seenDays.has(s.day)) fail(`${at}: two slots on the same day`);
  if (s.day < prevDay) fail(`${at}: days must be in order`);
  if (seenSlots.has(s.slot)) fail(`${at}: slot id used twice; it is the utm_content`);
  if (!/^[a-z0-9-]+$/.test(s.slot)) fail(`${at}: slot id must be lowercase letters, digits and dashes`);
  seenDays.add(s.day); seenSlots.add(s.slot); prevDay = s.day;
  if (!existsSync(join(repo, s.media))) fail(`${at}: media not found: ${s.media}`);
  if (!ROUTES.has(s.landing)) fail(`${at}: landing ${s.landing} is not a route in frontend/src/App.jsx`);
  if (typeof s.caption?.[s.lang] !== 'function') fail(`${at}: no ${s.lang} caption`);
  if (!s.platforms.length) fail(`${at}: no platforms`);
  for (const p of s.platforms) if (!NETWORKS[p]) fail(`${at}: unknown platform ${p}`);
  if (s.platforms.includes('youtube')) {
    if (!s.youtubeTitle) fail(`${at}: on YouTube but has no youtubeTitle`);
    else if ([...s.youtubeTitle].length > 100) fail(`${at}: YouTube titles are capped at 100 characters`);
  }
  // Metricool's tiktokData has a title field (no length limit stated, not
  // marked required), so every TikTok slot carries one: one plain line, no
  // hashtags or links, because it is a title, not a second caption.
  if (s.platforms.includes('tiktok')) {
    if (!s.tiktokTitle) fail(`${at}: on TikTok but has no tiktokTitle`);
    else if (/[\n#]|https?:\/\//.test(s.tiktokTitle)) fail(`${at}: tiktokTitle must be one plain line with no hashtags or links`);
  }
  if (s.line) {
    if (seenWeeks.has(s.line.week)) fail(`${at}: LINE week ${s.line.week} used twice`);
    seenWeeks.add(s.line.week);
  }
}
for (const list of Object.values(EXTRAS)) {
  for (const e of list) for (const f of e.media) if (!existsSync(join(repo, f))) fail(`extra ${e.slot}: media not found: ${f}`);
  for (const e of list) if (!ROUTES.has(e.landing)) fail(`extra ${e.slot}: landing ${e.landing} is not a route`);
}

// ----------------------------------------------------------------- texts ---

// Caption lines for one app: the main language, then (on Instagram and
// Facebook) any other language the slot has.
function captionLines(s, network) {
  const langs = [s.lang, ...Object.keys(s.caption).filter((l) => l !== s.lang)];
  return (BILINGUAL.has(network) ? langs : [s.lang]).map((l) => ({ lang: l, text: s.caption[l]() }));
}

// The exact text posted on one app.
function postText(s, network) {
  const { bioTail, linkInText, hashtags } = NETWORKS[network];
  const lines = captionLines(s, network);
  // The bio pointer goes on the last caption line, in that line's language.
  if (bioTail) {
    const last = lines[lines.length - 1];
    last.text = `${last.text} ${BIO_TAIL[last.lang]}`;
  }
  const out = lines.map((l) => l.text);
  if (linkInText) out.push(link(network, s.slot, s.landing));
  if (hashtags) out.push(s.hashtags.join(' '));
  return out.join('\n');
}

const lineText = (s) => `${s.line.text()}\n${link('line', s.slot, s.landing)}`;

// ----------------------------------------------------------------- queue ---

const posts = [];
for (const s of SLOTS) {
  for (const network of ORDER.filter((n) => s.platforms.includes(n))) {
    const linkInText = NETWORKS[network].linkInText;
    posts.push({
      id: `d${pad(s.day)}-${network}-${s.slot}`,
      network,
      day: s.day,
      dayOffset: s.day - 1,
      localTime: NETWORKS[network].time,
      mediaPath: s.media,
      // Metricool notes that TikTok's API drops line breaks, which would
      // run the caption's last word into the first hashtag. So TikTok queue
      // text is joined with spaces. TikTok.txt keeps its line breaks because
      // it is pasted by hand, not sent through the API.
      text: network === 'tiktok' ? postText(s, network).split('\n').join(' ') : postText(s, network),
      // Only where the URL is actually printed in the post. TikTok and
      // Instagram captions can't hold a clickable link and their bios hold
      // one fixed URL (utm_campaign=bio in the SETUP block), so a per-slot
      // link here would be a number nobody can ever click. Their visits are
      // attributed per channel, through the bio, until a link-in-bio page
      // exists. An earlier version of this queue kept a per-slot Instagram
      // link, and review flagged it as data that looked real but went nowhere.
      link: linkInText ? link(network, s.slot, s.landing) : null,
      linkInText,
      youtubeTitle: network === 'youtube' ? s.youtubeTitle : null,
      tiktokTitle: network === 'tiktok' ? s.tiktokTitle : null,
      utmContent: s.slot,
      networkData: networkData(network, s),
    });
  }
}

// LINE is not a Metricool network, so its broadcasts sit apart from `posts`
// and are sent from LINE Official Account Manager. They are here so a dated
// copy gives the owner their dates too.
const manual = SLOTS.filter((s) => s.line)
  .sort((a, b) => a.line.week - b.line.week)
  .map((s) => ({
    id: `w${pad(s.line.week)}-line-${s.slot}`,
    network: 'line',
    week: s.line.week,
    dayOffset: (s.line.week - 1) * 7,
    localTime: LINE_TIME,
    mediaPath: s.media,
    text: lineText(s),
    link: link('line', s.slot, s.landing),
    utmContent: s.slot,
  }));

const queue = {
  about: 'LEXIS posting queue, generated by brand-kit/schedule/build.mjs from posts.mjs. Offsets only: run build.mjs --start=YYYY-MM-DD for dates. Nothing in this file has been sent to Metricool or any app. See brand-kit/schedule/README.md.',
  timezone: TZ,
  window: WINDOW,
  linkFormat: `${SITE}<landing>?utm_source=<network>&utm_medium=social&utm_campaign=daily-posts&utm_content=<slot>`,
  posts,
  manual,
};

for (const e of [...posts, ...manual]) {
  if (e.localTime < WINDOW[0] || e.localTime > WINDOW[1]) fail(`${e.id}: ${e.localTime} is outside ${WINDOW.join('-')} Bangkok`);
  // A URL where it can't be clicked is dead text that looks like a promise,
  // so none may slip into a TikTok or Instagram post, as text or as `link`.
  const noLinkHere = NETWORKS[e.network] && !NETWORKS[e.network].linkInText;
  if (e.network === 'tiktok' && e.text.includes('\n')) fail(`${e.id}: TikTok queue text has a line break, which TikTok's API drops`);
  if (noLinkHere && (e.link || /https?:\/\/|learnwithlexis\.com/i.test(e.text))) fail(`${e.id}: ${e.network} post carries a link it can't use`);
  if (e.link) {
    const u = new URL(e.link);
    for (const k of UTM_KEYS) if (!u.searchParams.get(k)) fail(`${e.id}: link is missing ${k}`);
    if (u.searchParams.get('utm_source') !== e.network) fail(`${e.id}: utm_source is not ${e.network}`);
  }
}

// ---------------------------------------------------------- text files ---

const lastDay = SLOTS[SLOTS.length - 1].day;

function dailyPosts() {
  const out = [
    `LEXIS: ONE POST A DAY, ${lastDay} DAYS`,
    'Post between 7pm and 9pm Thailand time.',
    'Same video on TikTok, then Instagram Reels, then YouTube Shorts, then Facebook, unless the day says "Only on".',
    'Copy the caption under each day exactly. TikTok, Instagram and YouTube Shorts can\'t click links in a caption, so there end the caption with: ลิงก์ในโปรไฟล์ (Link in bio. on English days). On YouTube and Facebook, also paste that app\'s Link line under the caption; on Facebook it replaces the ลิงก์ในโปรไฟล์ ending.',
    // Files are named, not given a folder: in the repo they sit in
    // platforms/, in the phone pack all of them sit together in 4-captions/.
    'The exact text for each app, ending included, is in that app\'s own file: TikTok.txt, Instagram.txt, YouTube.txt, Facebook.txt.',
    'Pin Day 1 to the top of the TikTok, Instagram and Facebook profiles (YouTube Shorts and LINE can\'t pin a post).',
    'LINE gets one broadcast a week, not a daily post: see LINE.txt.',
  ].join('\n');
  const days = SLOTS.map((s) => {
    const lines = [`=== DAY ${s.day} === video: ${s.phone}`];
    const on = ORDER.filter((n) => s.platforms.includes(n));
    if (on.length !== ORDER.length) lines.push(`Only on: ${on.map((n) => NETWORKS[n].label).join(', ')}`);
    lines.push(s.caption[s.lang]());
    for (const n of on) if (NETWORKS[n].linkInText) lines.push(`Link (${NETWORKS[n].label}): ${link(n, s.slot, s.landing)}`);
    lines.push(s.hashtags.join(' '));
    return lines.join('\n');
  });
  const after = [
    `=== AFTER DAY ${lastDay} ===`,
    'Start again from Day 1, or tell Claude which video got the most views and get more like it.',
    'Posts for any day (Community swipe posts, Instagram stories, expat Facebook groups) are at the end of Instagram.txt and Facebook.txt.',
  ].join('\n');
  return [out, ...days, after, GENERATED].join('\n\n') + '\n';
}

function platformPost(s, network) {
  const file = basename(s.media);
  switch (network) {
    case 'tiktok': case 'facebook':
      return `DAY ${s.day}: ${file}\n${postText(s, network)}`;
    case 'instagram':
      return `DAY ${s.day}: REEL ${file}\n${postText(s, network)}`;
    case 'youtube':
      return `DAY ${s.day}: ${file}\nTitle: ${s.youtubeTitle}\nDescription: ${postText(s, network)}`;
    default: throw new Error(network);
  }
}

function extraPost(e, network) {
  if (e.linkOnly) return `${e.heading}\n${link(network, e.slot, e.landing)}`;
  const body = network === 'instagram'
    ? [e.text(), e.hashtags.join(' ')]
    : [e.text(), link(network, e.slot, e.landing)];
  return [e.heading, ...body].join('\n');
}

function platformFile(pf) {
  const parts = [pf.header(), pf.intro];
  if (pf.network === 'line') {
    const weeks = SLOTS.filter((s) => s.line).sort((a, b) => a.line.week - b.line.week);
    parts.push(...weeks.map((s) => `WEEK ${s.line.week}: ${basename(s.media)}\n${lineText(s)}`));
    parts.push(pf.footer(weeks[weeks.length - 1].line.week));
  } else {
    const mine = SLOTS.filter((s) => s.platforms.includes(pf.network));
    parts.push(...mine.map((s) => platformPost(s, pf.network)));
    const extras = EXTRAS[pf.network] ?? [];
    if (extras.length) parts.push('EXTRA POSTS: any day, once or twice a week, not part of the daily order.', ...extras.map((e) => extraPost(e, pf.network)));
    parts.push(pf.footer(mine[mine.length - 1].day));
  }
  parts.push(GENERATED);
  return parts.join('\n\n') + '\n';
}

const outputs = new Map([
  [join(phoneDir, 'DAILY-POSTS.txt'), dailyPosts()],
  ...PLATFORM_FILES.map((pf) => [join(phoneDir, 'platforms', pf.file), platformFile(pf)]),
  [join(here, 'metricool-queue.json'), JSON.stringify(queue, null, 2) + '\n'],
]);

// ------------------------------------------------------------------- run ---

if (problems.length) {
  console.error(`build.mjs: ${problems.length} problem(s), nothing written:\n- ${problems.join('\n- ')}`);
  process.exit(1);
}

const args = process.argv.slice(2);
const opt = (name) => args.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3);
for (const a of args) {
  if (!/^--(start|out)=/.test(a) && a !== '--check') {
    console.error(`build.mjs: unknown argument ${a}`);
    process.exit(2);
  }
}

// YYYY-MM-DD plus whole days, done in UTC so the host's timezone can't
// shift a date by one.
function addDays(ymd, n) {
  const [y, mo, d] = ymd.split('-').map(Number);
  return new Date(Date.UTC(y, mo - 1, d + n)).toISOString().slice(0, 10);
}

const start = opt('start');
if (start !== undefined) {
  // Reject what Date would quietly roll over (2026-02-30 becoming 03-02).
  if (!/^\d{4}-\d{2}-\d{2}$/.test(start) || addDays(start, 0) !== start) {
    console.error(`build.mjs: --start must be a real date as YYYY-MM-DD, got "${start}"`);
    process.exit(2);
  }
  // `date` and `publicationDate` are the two shapes createScheduledPost
  // takes; both are given so the scheduler copies rather than converts.
  const stamp = (e) => {
    const dateTime = `${addDays(start, e.dayOffset)}T${e.localTime}:00`;
    return { ...e, date: `${dateTime}${TZ_OFFSET}`, publicationDate: { dateTime, timezone: TZ } };
  };
  const datedQueue = { ...queue, startDate: start, posts: posts.map(stamp), manual: manual.map(stamp) };
  // Metricool refuses past dates, so say so here rather than mid-run.
  const past = [...datedQueue.posts, ...datedQueue.manual].filter((e) => Date.parse(e.date) < Date.now()).length;
  if (past) console.error(`build.mjs: warning: ${past} entr${past === 1 ? 'y is' : 'ies are'} already in the past for --start=${start}`);
  const json = JSON.stringify(datedQueue, null, 2) + '\n';
  const out = opt('out');
  if (out) writeFileSync(out, json);
  else process.stdout.write(json);
  process.exit(0);
}

if (args.includes('--check')) {
  const stale = [...outputs].filter(([f, text]) => !existsSync(f) || readFileSync(f, 'utf8') !== text).map(([f]) => relative(repo, f));
  if (stale.length) {
    console.error(`build.mjs --check: out of date, run node brand-kit/schedule/build.mjs:\n- ${stale.join('\n- ')}`);
    process.exit(1);
  }
  console.log(`build.mjs --check: ${outputs.size} files up to date`);
  process.exit(0);
}

for (const [f, text] of outputs) writeFileSync(f, text);
console.log(`wrote ${outputs.size} files: ${posts.length} queued posts over ${lastDay} days, ${manual.length} LINE broadcasts`);
